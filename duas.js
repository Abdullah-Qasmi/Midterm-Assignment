const duasGrid = document.getElementById("duasGrid");
const duaSearch = document.getElementById("duaSearch");
const duaCounter = document.getElementById("duaCounter");
const noResults = document.getElementById("noResults");


// MODAL ELEMENTS

const duaModal = document.getElementById("duaModal");
const closeModal = document.getElementById("closeModal");

const modalNumber = document.getElementById("modalNumber");
const modalTitle = document.getElementById("modalTitle");
const modalArabic = document.getElementById("modalArabic");
const modalTransliteration = document.getElementById("modalTransliteration");
const modalEnglish = document.getElementById("modalEnglish");
const modalUrdu = document.getElementById("modalUrdu");
const modalReference = document.getElementById("modalReference");


// =====================================================
// DISPLAY DUAS
// =====================================================

function displayDuas(list) {

    duasGrid.innerHTML = "";

    duaCounter.textContent = `Showing ${list.length} Duas`;


    if (list.length === 0) {

        noResults.classList.remove("hidden");

        return;

    }


    noResults.classList.add("hidden");


    list.forEach(function(dua) {

        const card = document.createElement("article");

        card.className =
            "bg-white rounded-2xl border border-[#e3e3de] p-6 shadow-sm hover:shadow-xl hover:-translate-y-1 transition-all duration-300 cursor-pointer";


        card.innerHTML = `

            <div class="flex justify-between items-center mb-5">

                <span class="text-xs font-bold text-[#c89b25] bg-[#c89b25]/10 px-3 py-1 rounded-md">

                    Dua #${dua.id}

                </span>

                <span class="material-symbols-outlined text-[#0f5132]">
                    auto_stories
                </span>

            </div>


            <h2 class="text-xl font-bold text-[#0f5132] mb-6">

                ${dua.title}

            </h2>


            <div class="bg-[#f7f8f3] rounded-xl p-5 mb-5">

                <p
                    dir="rtl"
                    class="font-serif text-2xl leading-loose text-[#0f5132] text-right"
                >
                    ${dua.arabic}
                </p>

            </div>


            <div class="border-t border-[#e3e3de] pt-4 flex justify-between items-center">

                <span class="text-xs text-[#68776e]">

                    ${dua.reference}

                </span>


                <span class="text-sm font-semibold text-[#0f5132]">

                    Read More →

                </span>

            </div>

        `;


        card.addEventListener("click", function() {

            openDua(dua);

        });


        duasGrid.appendChild(card);

    });

}


// =====================================================
// OPEN MODAL
// =====================================================

function openDua(dua) {

    modalNumber.textContent = `Dua #${dua.id}`;

    modalTitle.textContent = dua.title;

    modalArabic.textContent = dua.arabic;

    modalTransliteration.textContent = dua.transliteration;

    modalEnglish.textContent = dua.english;

    modalUrdu.textContent = dua.urdu;

    modalReference.textContent = dua.reference;


    duaModal.classList.remove("hidden");

    document.body.style.overflow = "hidden";

}


// =====================================================
// CLOSE MODAL
// =====================================================

function closeDuaModal() {

    duaModal.classList.add("hidden");

    document.body.style.overflow = "auto";

}


closeModal.addEventListener("click", closeDuaModal);


duaModal.addEventListener("click", function(event) {

    if (event.target === duaModal) {

        closeDuaModal();

    }

});


// =====================================================
// ESC KEY
// =====================================================

document.addEventListener("keydown", function(event) {

    if (event.key === "Escape") {

        closeDuaModal();

    }

});


// =====================================================
// SEARCH
// =====================================================

duaSearch.addEventListener("input", function() {

    const searchText = this.value.toLowerCase().trim();


    const filtered = duas.filter(function(dua) {

        return (

            dua.title.toLowerCase().includes(searchText) ||

            dua.arabic.includes(searchText) ||

            dua.transliteration.toLowerCase().includes(searchText) ||

            dua.english.toLowerCase().includes(searchText) ||

            dua.urdu.includes(searchText) ||

            dua.reference.toLowerCase().includes(searchText)

        );

    });


    displayDuas(filtered);

});


// =====================================================
// DARK MODE
// =====================================================

const themeToggle = document.getElementById("themeToggle");

const themeIcon = document.getElementById("themeIcon");


themeToggle.addEventListener("click", function() {

    document.body.classList.toggle("dark-mode");


    if (document.body.classList.contains("dark-mode")) {

        themeIcon.textContent = "light_mode";

    } else {

        themeIcon.textContent = "dark_mode";

    }

});


// =====================================================
// INITIAL LOAD
// =====================================================

displayDuas(duas);