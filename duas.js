function openDua(dua) {

    modalNumber.textContent =
        `Dua ${dua.id}`;

    modalTitle.textContent =
        dua.title;

    modalArabic.textContent =
        dua.arabic;

    modalTransliteration.textContent =
        dua.transliteration;

    modalEnglish.textContent =
        dua.english;

    modalUrdu.textContent =
        dua.urdu;

    modalReference.textContent =
        dua.reference;


    duaModal.classList.remove("hidden");

    document.body.style.overflow =
        "hidden";

}


// =====================================================
// CLOSE MODAL
// =====================================================

function closeDuaModal() {

    duaModal.classList.add("hidden");

    document.body.style.overflow = "";

}


closeModal.addEventListener(
    "click",
    closeDuaModal
);


duaModal.addEventListener(
    "click",
    function(event) {

        if (event.target === duaModal) {

            closeDuaModal();

        }

    }
);


// =====================================================
// ESCAPE KEY
// =====================================================

document.addEventListener(
    "keydown",
    function(event) {

        if (
            event.key === "Escape" &&
            !duaModal.classList.contains("hidden")
        ) {

            closeDuaModal();

        }

    }
);


// =====================================================
// FAVORITE FUNCTION
// =====================================================

function toggleDuaFavorite(
    id,
    button
) {

    const index =
        duaFavorites.indexOf(id);


    if (index === -1) {

        duaFavorites.push(id);

    } else {

        duaFavorites.splice(index, 1);

    }


    localStorage.setItem(
        "duaFavorites",
        JSON.stringify(duaFavorites)
    );


    const icon =
        button.querySelector(
            ".material-symbols-outlined"
        );


    icon.textContent =
        duaFavorites.includes(id)
            ? "favorite"
            : "favorite_border";

}


// =====================================================
// AUDIO / LISTEN
// =====================================================

function speakDua(dua) {

    if (!("speechSynthesis" in window)) {

        alert(
            "Sorry, audio is not supported in this browser."
        );

        return;

    }


    // Stop previous audio
    window.speechSynthesis.cancel();


    // Speak Arabic first
    const arabicSpeech =
        new SpeechSynthesisUtterance(
            dua.arabic
        );

    arabicSpeech.lang = "ar-SA";

    arabicSpeech.rate = 0.75;

    arabicSpeech.pitch = 1;


    // Then English translation
    const englishSpeech =
        new SpeechSynthesisUtterance(
            dua.english
        );

    englishSpeech.lang = "en-US";

    englishSpeech.rate = 0.85;

    englishSpeech.pitch = 1;


    // Arabic first, then English
    window.speechSynthesis.speak(
        arabicSpeech
    );

    window.speechSynthesis.speak(
        englishSpeech
    );

}


