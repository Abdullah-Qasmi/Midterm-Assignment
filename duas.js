// DISPLAY DUAS
// =====================================================

function displayDuas(list) {

    duasGrid.innerHTML = "";

    duaCounter.textContent =
        `Showing ${list.length}/40`;

    if (list.length === 0) {

        noResults.classList.remove("hidden");

        return;

    }

    noResults.classList.add("hidden");

    list.forEach(function(dua) {

        duasGrid.appendChild(
            createDuaCard(dua)
        );

    });

}


// =====================================================
// SEARCH
// =====================================================

function filterDuas(query) {

    const q = query.toLowerCase().trim();

    return duas.filter(function(dua) {

        return (

            dua.title
                .toLowerCase()
                .includes(q)

            ||

            dua.arabic
                .includes(q)

            ||

            dua.transliteration
                .toLowerCase()
                .includes(q)

            ||

            dua.english
                .toLowerCase()
                .includes(q)

            ||

            dua.urdu
                .includes(q)

            ||

            dua.reference
                .toLowerCase()
                .includes(q)

            ||

            dua.id
                .toString()
                .includes(q)

        );

    });

}


duaSearch.addEventListener("input", function() {

    const filtered =
        filterDuas(this.value);

    displayDuas(filtered);

});


